"""
services/latency_service.py against Postgres: percentiles, means per request
and the slices of a route's series, from rows shaped like the backend's.

The table is created here as the backend's migration 0037 creates it (the
backend owns the schema; this suite only reads it).
"""

from datetime import datetime, timedelta, timezone
import json

import pytest

from services.latency_service import build_overview, build_route

pytestmark = pytest.mark.integration

NOW = datetime(2026, 10, 20, 18, 30, tzinfo=timezone.utc)
MATCHUP = "/v1/matchups/live/{team_id}"
RANKINGS = "/v1/rankings"

TABLE = """
CREATE SCHEMA IF NOT EXISTS ops;
CREATE TABLE IF NOT EXISTS ops.request_timings (
    id           bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at   timestamp with time zone NOT NULL,
    service      text             NOT NULL,
    method       text             NOT NULL,
    route        text             NOT NULL,
    status_code  smallint         NOT NULL,
    duration_ms  double precision NOT NULL,
    parts        jsonb            NOT NULL DEFAULT '{}'::jsonb,
    calls        jsonb            NOT NULL DEFAULT '{}'::jsonb,
    trace_id     varchar(32),
    version      text
);
"""


@pytest.fixture
def timings(integration_db):
    integration_db.execute_sql(TABLE)
    integration_db.execute_sql("TRUNCATE ops.request_timings")

    def add(route, minutes_ago, duration, parts, *, status=200, calls=None, service="api", trace_id=None):
        integration_db.execute_sql(
            "INSERT INTO ops.request_timings (started_at, service, method, route, status_code, duration_ms,"
            " parts, calls, trace_id, version) VALUES (%s, %s, 'GET', %s, %s, %s, %s, %s, %s, 'abc123')",
            (NOW - timedelta(minutes=minutes_ago), service, route, status, duration,
             json.dumps(parts), json.dumps(calls or {}), trace_id),
        )

    yield add
    integration_db.execute_sql("DROP TABLE ops.request_timings")


def test_overview_ranks_routes_by_time_and_averages_their_parts(timings):
    for minutes_ago, espn in ((10, 300.0), (70, 500.0), (130, 900.0)):
        timings(MATCHUP, minutes_ago, espn + 100.0, {"espn": espn, "app": 100.0}, calls={"espn": 1})
    timings(MATCHUP, 20, 50.0, {"app": 50.0}, status=502)
    for minutes_ago in range(0, 10):
        timings(RANKINGS, minutes_ago, 10.0, {"postgres": 4.0, "app": 6.0}, calls={"postgres": 2})
    timings(RANKINGS, 60 * 25, 9999.0, {"app": 9999.0})  # outside the day
    timings(RANKINGS, 5, 9999.0, {"app": 9999.0}, service="data-platform")  # another service

    data = build_overview("24h", now=NOW)

    assert data.available is True
    assert [r.route for r in data.routes] == [MATCHUP, RANKINGS]
    matchup, rankings = data.routes
    assert (matchup.requests, matchup.errors, matchup.max_ms) == (4, 1, 1000.0)
    assert matchup.p50_ms == pytest.approx(500.0)  # between 400 and 600
    assert matchup.parts == {"espn": 425.0, "app": 87.5}
    assert sum(matchup.parts.values()) == pytest.approx(matchup.mean_ms)
    assert matchup.calls == {"espn": 0.75}
    assert (rankings.requests, rankings.p95_ms, rankings.calls) == (10, 10.0, {"postgres": 2.0})
    assert data.totals.requests == 14 and data.totals.errors == 1


def test_route_detail_has_every_slice_and_the_slowest_requests(timings):
    timings(MATCHUP, 10, 400.0, {"espn": 300.0, "app": 100.0}, trace_id="0af7651916cd43dd8448eb211c80319c")
    timings(MATCHUP, 15, 1200.0, {"espn": 1100.0, "wait": 50.0, "app": 50.0})
    timings(MATCHUP, 180, 200.0, {"espn": 150.0, "app": 50.0})
    timings(RANKINGS, 10, 5000.0, {"app": 5000.0})

    data = build_route("GET", MATCHUP, "24h", now=NOW)

    assert data.route.requests == 3 and data.bin_seconds == 3600
    assert len(data.series) == 25
    busy = [s for s in data.series if s.requests]
    assert [s.requests for s in busy] == [1, 2]
    assert busy[-1].parts == {"espn": 700.0, "wait": 25.0, "app": 75.0}
    assert [r.duration_ms for r in data.slowest] == [1200.0, 400.0, 200.0]
    assert data.slowest[0].parts["wait"] == 50.0
    assert data.slowest[1].trace_id == "0af7651916cd43dd8448eb211c80319c"


def test_without_the_table_the_page_is_told_it_is_unavailable(integration_db):
    integration_db.execute_sql("DROP TABLE IF EXISTS ops.request_timings")

    assert build_overview("24h", now=NOW).available is False
    assert build_route("GET", MATCHUP, "1h", now=NOW).route is None
